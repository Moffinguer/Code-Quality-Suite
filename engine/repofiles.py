def check(root, rel, data=None, branch=""):
    """(errors, warnings) for one file of the repository; ([], []) for files it does not know."""
    br = _branches(data)
    base = os.path.basename(rel)
    errors, warnings = [], []
    known = {
        br["version_file"],
        br["changelog_file"],
        br["readme_file"],
        "pom.xml",
        "CITATION.cff",
        *CODEOWNERS_PLACES,
        *LICENSE_NAMES,
    }
    if rel not in known and base not in NAMES:
        return errors, warnings
    text = _read(root, rel)
    if text is None:
        return errors, warnings
    vfile, cfile, rfile = br["version_file"], br["changelog_file"], br["readme_file"]
    if vfile and rel == vfile:
        _check_version(root, text, br, data, branch, errors, warnings)
    elif rel == "pom.xml" and vfile and br["pom_version"] != "off":
        _check_pom(root, vfile, errors)
    elif cfile and rel == cfile:
        _check_changelog(root, text, br, errors, warnings)
    elif rfile and rel == rfile:
        _check_readme(root, text, cfile, errors, warnings)
    elif rel == "CITATION.cff":
        _check_citation(root, text, cfile, errors, warnings)
    elif rel in CODEOWNERS_PLACES:
        _check_codeowners(text, errors, warnings)
    elif rel in LICENSE_NAMES:
        _check_license(text, errors, warnings)
    if base in NAMES or rel in CODEOWNERS_PLACES or rel in LICENSE_NAMES:
        n = text.count(FILL)
        if n:
            warnings.append(
                f"{n} part(s) still to write (marked '{FILL}'); fill them or delete the markers"
            )
    return errors, warnings


def _check_pom(root, vfile, errors):
    """Check that the pom.xml version matches the version file.

    Args:
        root: repository root.
        vfile: name of the version file.
        errors: list the findings are appended to.
    """
    v = (_read(root, vfile) or "").strip()
    p = MV.read_versions(root, vfile).get("pom.xml")
    if v and p and p not in (v, v + "-SNAPSHOT"):
        errors.append(
            f"<version>{p}</version> does not match {vfile} ({v}); "
            f"set it: mvn versions:set -DnewVersion={v} -DgenerateBackupPoms=false"
        )


def _unreleased(root, version, br):
    """Tell whether no git tag exists yet for a version.

    Args:
        root: repository root.
        version: the version to look for.
        br: the branches policy (key `tag`, default `{version}`).

    Returns:
        bool: True only when git works in root and no tag of that version exists; False when
        it is tagged, and False too (silent) without git, a repository or on any error.
    """
    git = ["git", "-C", root]
    if not _git(git, "rev-parse", "--git-dir").strip():
        return False
    names = {(br.get("tag") or "{version}").replace("{version}", version)}
    custom = _git(git, "config", f"qs.release.{version}.tag").strip()
    if custom:
        names.add(custom)
    return not names & set(_git(git, "tag", "-l").split())


def _check_changelog(root, text, br, errors, warnings):
    """Validate CHANGELOG.md, flagging 4.x-format lines in the entry being written.

    The entry being written is the topmost section when its version has no git tag yet (tag
    name from policy `branches.tag`, default `{version}`, or `qs.release.<v>.tag`). Tagged
    sections are released history and stay silent (the 4.x lines of 4.2.1 are legitimate
    there). Without git, a repository or on a git error nothing counts as new.

    Args:
        root: repository root.
        text: the CHANGELOG.md content.
        errors: list the errors are appended to.
        warnings: list the warnings are appended to.
        br: the branches policy (version file name, tag template).
    """
    top = (CL.versions(text) or [None])[0]
    vfile = br["version_file"]
    v = (_read(root, vfile) or "").strip() if vfile else ""
    new = bool(top and _unreleased(root, top, br))
    e, w = CL.validate(text, top if new else None)
    errors += e
    warnings += w
    if top and SV.valid(v) and SV.valid(top) and SV.compare(top, v) > 0:
        warnings.append(f"the last release ({top}) is newer than {vfile} ({v})")


def _check_readme(root, text, cfile, errors, warnings):
    """Check the README version badge against the last release of the changelog.

    Args:
        root: repository root.
        text: the README content.
        cfile: name of the changelog file, or empty.
        errors: list the errors are appended to.
        warnings: list the warnings are appended to.
    """
    bv = CL.badge_version(text)
    top = (CL.versions(_read(root, cfile) or "") or [None])[0] if cfile else None
    if bv is None:
        warnings.append(
            f"no version badge ('{CL.BADGE_START}...{CL.BADGE_END}'); git release adds it"
        )
    elif not SV.valid(bv):
        errors.append(f"version badge '{bv}' is not a semantic version")
    elif top and bv != top:
        errors.append(f"the version badge says {bv} but the last release in {cfile} is {top}")


def _check_license(text, errors, warnings):
    """Check that the license file is not empty nor a template.

    Args:
        text: the license content.
        errors: list the errors are appended to.
        warnings: list the warnings are appended to.
    """
    if not text.strip():
        errors.append("the license file is empty")
    elif re.search(
        r"\[(year|yyyy|fullname|name of copyright owner)\]|<(year|copyright holders?)>",
        text,
        re.I,
    ):
        warnings.append("the license still has template placeholders ([year], [fullname]...)")


def _check_version(root, text, br, data, branch, errors, warnings):  # noqa: PLR0913, PLR0917 - internal collector signature
    """Validate the version file and collect findings.

    Args:
        root: the repository root.
        text: the file text.
        br: the effective branch settings.
        data: the rules file.
        branch: the current branch.
        errors: list that receives errors.
        warnings: list that receives warnings.
    """
    lines = text.splitlines()
    v = text.strip()
    if len([ln for ln in lines if ln.strip()]) != 1:
        errors.append("must hold one line: the version, e.g. 6.22.6")
        return
    if not SV.valid(v):
        errors.append(
            f"'{v}' is not a semantic version (MAJOR.MINOR.PATCH, https://semver.org; no 'v' "
            f"prefix)"
        )
        return
    if not text.endswith("\n") or text != v + "\n":
        warnings.append("write only the version and a final newline")
    want = branch_version(branch, data)
    if want and want != v:
        errors.append(f"branch '{branch}' belongs to version {want} but this file says {v}")
    if br["pom_version"] != "off":
        p = MV.read_versions(root, "").get("pom.xml")
        if p and p not in (v, v + "-SNAPSHOT"):
            errors.append(
                f"pom.xml has <version>{p}</version>; set it: "
                f"mvn versions:set -DnewVersion={v} -DgenerateBackupPoms=false"
            )
    top = (
        (CL.versions(_read(root, br["changelog_file"]) or "") or [None])[0]
        if br["changelog_file"]
        else None
    )
    if top and SV.valid(top) and SV.compare(top, v) > 0:
        errors.append(f"{v} is older than the last release in {br['changelog_file']} ({top})")


def _check_citation(root, text, cfile, errors, warnings):
    """Validate CITATION.cff and collect findings.

    Args:
        root: the repository root.
        text: the file text.
        cfile: the changelog file name.
        errors: list that receives errors.
        warnings: list that receives warnings.
    """
    try:
        import yaml  # noqa: PLC0415 - optional dependency, loaded on demand
    except ImportError:
        return
    try:
        doc = yaml.safe_load(text)
    except yaml.YAMLError as e:
        errors.append("not valid YAML: " + str(e).replace("\n", " ")[:200])
        return
    if not isinstance(doc, dict):
        errors.append("must be a YAML mapping (cff-version, message, title, authors...)")
        return
    for k in ("cff-version", "message", "title", "authors"):
        if k not in doc:
            errors.append(f"required key '{k}' is missing (Citation File Format 1.2.0)")
    authors = doc.get("authors")
    if "authors" in doc and (not isinstance(authors, list) or not authors):
        errors.append("'authors' must be a non-empty list")
    for i, a in enumerate(authors if isinstance(authors, list) else [], 1):
        if not isinstance(a, dict) or not (a.get("family-names") or a.get("name")):
            errors.append(f"author {i} needs 'family-names' (a person) or 'name' (an entity)")
    v = doc.get("version")
    if v is not None and not SV.valid(str(v)):
        warnings.append(f"version '{v}' is not a semantic version")
    d = doc.get("date-released")
    if (
        d is not None
        and not isinstance(d, datetime.date)
        and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(d))
    ):
        errors.append(f"date-released '{d}' must be YYYY-MM-DD")
    top = (CL.versions(_read(root, cfile) or "") or [None])[0] if cfile else None
    if v is not None and top and str(v) != top:
        warnings.append(
            f"version {v} differs from the last release in {cfile} ({top}); git release updates it"
        )


OWNER = re.compile(r"^(@[A-Za-z0-9][A-Za-z0-9-]*(/[A-Za-z0-9][\w.-]*)*|[^@\s]+@[^@\s]+\.[^@\s]+)$")


def _check_codeowners(text, errors, warnings):
    """Validate a CODEOWNERS file and collect findings.

    Args:
        text: the file text.
        errors: list that receives errors.
        warnings: list that receives warnings.
    """
    for n, ln in enumerate(text.splitlines(), 1):
        s = ln.strip()
        if not s or s.startswith("#") or re.match(r"^\^?\[[^\]]+\](\[\d+\])?( .*)?$", s):
            continue  # comment or GitLab section
        parts = re.split(r"(?<!\\)\s+", s)
        pattern, owners = parts[0], parts[1:]
        if pattern.startswith("!") or "[" in pattern and "]" not in pattern:
            errors.append(f"line {n}: '{pattern}' is not a valid path pattern")
        bad = [o for o in owners if not o.startswith("#") and not OWNER.match(o)]
        if bad:
            errors.append(
                f"line {n}: owner(s) {' '.join(bad)} must be @user, @org/team or an e-mail"
            )
        if not owners:
            warnings.append(f"line {n}: '{pattern}' has no owner (nobody is asked to review it)")


