def _read(root, rel):
    """Read root/rel keeping line ends; None when it is missing or not UTF-8."""
    return textio.read_text(os.path.join(root, rel), newline="", default=None)


def _branches(data):
    """Branch settings of a rules file with the defaults filled in.

    Args:
        data: the parsed rules file (may be None).

    Returns:
        dict: the effective `branches` section.
    """
    br = dict((data or {}).get("branches") or {})
    for k, v in (
        ("version_file", "VERSION"),
        ("changelog_file", "CHANGELOG.md"),
        ("readme_file", "README.md"),
        ("pom_version", "update"),
        ("mainline", "develop"),
    ):
        br.setdefault(k, v)
    return br


def branch_version(branch, data):
    """The version a branch belongs to ('6.22.6' for '6.22.6/188858/login'), or None."""
    if not branch or "/" not in branch:
        return None
    first = branch.split("/", 1)[0]
    levels = _branches(data).get("levels") or [SV.BRANCH_RX]
    try:
        return first if re.match(levels[0], first) else None
    except re.error:
        return None


