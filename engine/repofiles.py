def _exists(root, name):
    """Find a convention file in the repository.

    Args:
        root: the repository root.
        name: the file name (CODEOWNERS is searched in its usual places).

    Returns:
        str: the relative path found, or None.
    """
    if name == "CODEOWNERS":
        return next((p for p in CODEOWNERS_PLACES if os.path.isfile(os.path.join(root, p))), None)
    if name == "LICENSE":
        return next((p for p in LICENSE_NAMES if os.path.isfile(os.path.join(root, p))), None)
    if name.endswith(".md"):
        low = name.lower()
        for p in (name, "docs/" + name, ".github/" + name):
            if os.path.isfile(os.path.join(root, p)):
                return p
        for p in os.listdir(root):
            if p.lower() == low:
                return p
        return None
    return name if os.path.isfile(os.path.join(root, name)) else None


def generate(root, gitcmd, data=None, names=None, force=False, dry=False, today=None):  # noqa: PLR0913, PLR0917 - public API, keyword options
    """Write the missing standard files.

    Args:
        root: repository root.
        gitcmd: git command prefix.
        data: parsed rules file.
        names: files to generate; None means all.
        force: overwrite existing files.
        dry: report without writing.
        today: date override.

    Returns:
        list: [(name, 'created' | 'exists: <path>' | 'would create')].
    """
    facts = gather(root, gitcmd, data, today)
    br = _branches(data)
    out = []
    for name in names or NAMES:
        if name not in NAMES:
            out.append((name, "unknown (choose from: " + ", ".join(NAMES) + ")"))
            continue
        target = {
            "VERSION": br["version_file"] or "VERSION",
            "CHANGELOG.md": br["changelog_file"] or "CHANGELOG.md",
            "README.md": br["readme_file"] or "README.md",
        }.get(name, name)
        have = _exists(root, target if name in ("VERSION", "CHANGELOG.md", "README.md") else name)
        if have and not force:
            out.append((name, f"exists: {have}"))
            continue
        text = t_changelog(facts, gitcmd) if name == "CHANGELOG.md" else TEMPLATES[name](facts)
        path = os.path.join(root, have or target)
        if dry:
            out.append((name, "would create" if not have else f"would overwrite {have}"))
            continue
        os.makedirs(os.path.dirname(path) or root, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        out.append((name, "created" if not have else f"regenerated {have}"))
    return out
