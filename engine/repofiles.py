_git = gitio.git_out


def gather(root, gitcmd, data=None, today=None):  # noqa: C901, PLR0912, PLR0915 - one linear fact collector
    """Everything the templates use. Missing facts stay empty; nothing here fails."""
    br = _branches(data)
    f = {
        "root": root,
        "today": (today or datetime.date.today()).isoformat(),
        "year": (today or datetime.date.today()).year,
        "name": os.environ.get("QS_REPO_NAME") or os.path.basename(os.path.abspath(root)),
        "description": "",
        "version": "",
        "released": "",
        "java": "",
        "packaging": "",
        "modules": [],
        "license": {},
        "group": "",
        "artifact": "",
        "build": "",
        "mvnw": os.path.isfile(os.path.join(root, "mvnw")),
        "frameworks": [],
        "authors": [],
        "owners": {},
        "tags": [],
        "trees": [],
        "unmerged": [],
        "origin": "",
        "web": ("", ""),
        "openapi": [],
        "endpoints": [],
        "mainline": br["mainline"],
    }
    f["dir"] = f["name"]  # the folder of the clone (the name may change below: pom <name>)
    pom = _read(root, "pom.xml")
    if pom is not None:
        f["build"] = "maven"
        info = MV.pom_info(pom)
        sp = info["spans"]

        def val(path, text=pom, spans=sp):
            """Whitespace-normalised text of the element at an XML path.

            Args:
                path: the element path.
                text: the pom text.
                spans: the element spans of that text.

            Returns:
                str: the text, or '' when absent.
            """
            s = spans.get(path)
            return re.sub(r"\s+", " ", text[s[0] : s[1]]).strip() if s else ""

        f["name"] = val("project/name") or info["artifact"] or f["name"]
        f["description"] = val("project/description")
        f["group"], f["artifact"] = info["group"] or "", info["artifact"] or ""
        f["packaging"] = val("project/packaging") or "jar"
        f["java"] = (
            val("project/properties/maven.compiler.release")
            or val("project/properties/java.version")
            or val("project/properties/maven.compiler.source")
        )
        f["license"] = {
            "name": val("project/licenses/license/name"),
            "url": val("project/licenses/license/url"),
        }
        pv = MV.read_versions(root, "").get("pom.xml") or ""
        f["version"] = pv.replace("-SNAPSHOT", "")
        parent = info["partifact"] or ""
        if "spring-boot" in parent or "spring-boot" in pom:
            f["frameworks"].append("Spring Boot")
        for fw, rx in (
            ("Jakarta EE / Java EE", r"<artifactId>(jakarta|javaee)[.-]"),
            ("JSP", r"jsp|jstl"),
            ("Hibernate / JPA", r"hibernate|persistence-api"),
            ("JUnit", r"junit"),
        ):
            if re.search(rx, pom, re.I) and fw not in f["frameworks"]:
                f["frameworks"].append(fw)
        for m in re.finditer(r"<module>\s*([^<]+?)\s*</module>", pom):
            mp = _read(root, os.path.join(m.group(1), "pom.xml"))
            if mp is None:
                f["modules"].append(
                    {"dir": m.group(1), "artifact": "", "packaging": "", "description": ""}
                )
                continue
            mi = MV.pom_info(mp)
            ms = mi["spans"]

            def mval(path, text=mp, spans=ms):
                """Whitespace-normalised text of the element at an XML path.

                Args:
                    path: the element path.
                    text: the pom text.
                    spans: the element spans of that text.

                Returns:
                    str: the text, or '' when absent.
                """
                s = spans.get(path)
                return re.sub(r"\s+", " ", text[s[0] : s[1]]).strip() if s else ""

            f["modules"].append(
                {
                    "dir": m.group(1),
                    "artifact": mi["artifact"] or "",
                    "packaging": mval("project/packaging") or "jar",
                    "description": mval("project/description") or mval("project/name"),
                }
            )
    pkg = _read(root, "package.json")
    if pkg is not None:
        try:
            pj = json.loads(pkg)
            f["build"] = f["build"] or "npm"
            if f["build"] == "npm":
                f["name"] = pj.get("name") or f["name"]
                f["description"] = pj.get("description") or ""
                f["version"] = pj.get("version") or ""
                lic = pj.get("license")
                f["license"] = {"name": lic if isinstance(lic, str) else "", "url": ""}
        except ValueError:
            pass
    vtxt = (_read(root, br["version_file"]) or "").strip() if br["version_file"] else ""
    if SV.valid(vtxt):
        f["version"] = vtxt
    # git: authors, owners, tags, branches, origin
    if gitcmd:
        per = collections.OrderedDict()
        for ln in _git(
            gitcmd, "log", "--no-merges", "--format=%an%x1f%ae%x1f%ad", "--date=format:%Y", "HEAD"
        ).splitlines():
            parts = ln.split("\x1f")
            if len(parts) != 3 or re.search(
                r"\[bot\]|noreply@github|dependabot|renovate", ln, re.I
            ):
                continue
            n, e, y = parts
            a = per.setdefault(
                e.lower(), {"name": n, "email": e, "commits": 0, "first": y, "last": y}
            )
            a["commits"] += 1
            a["first"] = min(a["first"], y)
            a["last"] = max(a["last"], y)
        f["authors"] = sorted(per.values(), key=lambda a: (-a["commits"], a["name"]))
        since = (datetime.date.today() - datetime.timedelta(days=730)).isoformat()
        counts = collections.defaultdict(collections.Counter)
        email = None
        for ln in _git(
            gitcmd,
            "log",
            "--no-merges",
            f"--since={since}",
            "--format=%x1e%ae",
            "--name-only",
            "HEAD",
        ).splitlines():
            if ln.startswith("\x1e"):
                email = ln[1:].strip()
            elif ln.strip() and email:
                top = ln.split("/", 1)[0] if "/" in ln else ""
                counts[top][email] += 1
        f["owners"] = {d: [e for e, _ in c.most_common(2)] for d, c in counts.items()}
        tags = []
        for ln in _git(
            gitcmd, "for-each-ref", "--format=%(refname:short)%09%(creatordate:short)", "refs/tags"
        ).splitlines():
            t, _, d = ln.partition("\t")
            if SV.valid(SV.strip_v(t)):
                tags.append((SV.strip_v(t), t, d))
        f["tags"] = sorted(tags, key=lambda x: SV.key(x[0]), reverse=True)
        heads = _git(
            gitcmd, "for-each-ref", "--format=%(refname)", "refs/heads", "refs/remotes/origin"
        ).splitlines()
        names = sorted(
            {re.sub(r"^refs/(heads|remotes/origin)/", "", h) for h in heads}
            - {"HEAD", "origin/HEAD"}
        )
        released = {t[0] for t in f["tags"]}
        f["trees"] = sorted(
            {
                n.split("/", 1)[0]
                for n in names
                if "/" in n and SV.valid(n.split("/", 1)[0]) and n.split("/", 1)[0] not in released
            },
            key=SV.key,
        )
        arch = (br.get("archive_prefix") or "unmerged") + "/"
        f["unmerged"] = [n for n in names if n.startswith(arch)]
        f["origin"] = _git(gitcmd, "config", "--get", "remote.origin.url").strip()
        f["web"] = web_url(f["origin"])
    clog = _read(root, br["changelog_file"]) if br["changelog_file"] else None
    f["released"] = (
        (CL.versions(clog) if clog else [])
        or [t[0] for t in f["tags"] if SV.is_release(t[0])]
        or [""]
    )[0]
    f["openapi"], f["endpoints"] = _api(root)
    return f


def web_url(origin):
    """(kind, https base) of the web page of a git remote; ('', '') when unknown."""
    o = (origin or "").strip()
    m = re.match(r"^git@ssh\.dev\.azure\.com:v3/([^/]+)/([^/]+)/(.+?)(\.git)?$", o)
    if m:
        return "azure", f"https://dev.azure.com/{m.group(1)}/{m.group(2)}/_git/{m.group(3)}"
    m = re.match(r"^(?:https?://)(?:[^@/]+@)?dev\.azure\.com/(.+?)/?$", o)
    if m:
        return "azure", "https://dev.azure.com/" + m.group(1)
    m = (
        re.match(r"^(?:ssh://)?(?:[^@/]+@)?([^:/]+)(?::\d+)?[:/](.+?)(\.git)?/?$", o)
        if not o.startswith("http")
        else re.match(r"^https?://(?:[^@/]+@)?([^/]+)/(.+?)(\.git)?/?$", o)
    )
    if not m:
        return "", ""
    host, path = m.group(1), m.group(2)
    kind = (
        "github"
        if "github" in host
        else "gitlab"
        if "gitlab" in host
        else "bitbucket"
        if "bitbucket" in host
        else "generic"
    )
    return kind, f"https://{host}/{path}"


def link_templates(origin, tag_url="", commit_url=""):
    """Return (tag URL template with {tag}, commit URL template with {commit}).

    Args:
        origin: the origin remote URL.
        tag_url: policy override for the tag URL; '-' means none.
        commit_url: policy override for the commit URL; '-' means none.

    Returns:
        tuple: the two templates, empty when unknown.
    """
    kind, base = web_url(origin)
    auto_tag = {
        "github": "{b}/releases/tag/{{tag}}",
        "gitlab": "{b}/-/tags/{{tag}}",
        "azure": "{b}?version=GT{{tag}}",
        "bitbucket": "{b}/src/{{tag}}",
    }.get(kind, "")
    auto_commit = {
        "github": "{b}/commit/{{commit}}",
        "gitlab": "{b}/-/commit/{{commit}}",
        "azure": "{b}/commit/{{commit}}",
        "bitbucket": "{b}/commits/{{commit}}",
    }.get(kind, "")
    t = "" if tag_url == "-" else tag_url or auto_tag.format(b=base)
    c = "" if commit_url == "-" else commit_url or auto_commit.format(b=base)
    return t, c


API_FILES = re.compile(r"(^|/)(openapi|swagger)[^/]*\.(ya?ml|json)$", re.I)
SPRING = re.compile(
    r"@(Get|Post|Put|Delete|Patch|Request)Mapping\s*(\(\s*(?:value\s*=\s*|path\s*=\s*)?\{?\s*\"([^\"]*)\")?"
)
JAXRS = re.compile(r"@(GET|POST|PUT|DELETE|PATCH)\b|@Path\s*\(\s*\"([^\"]*)\"")


def _api(root):
    """(OpenAPI files, endpoints found in Java annotations [(method, path, file)])."""
    specs, eps = [], []
    for dp, dn, fn in os.walk(root):
        dn[:] = [d for d in dn if d not in MV.SKIP_DIRS and not d.startswith(".")]
        for name in fn:
            rel = os.path.relpath(os.path.join(dp, name), root).replace(os.sep, "/")
            if API_FILES.search(rel):
                specs.append(rel)
            elif name.endswith(".java") and len(eps) < 200:
                text = _read(root, rel) or ""
                if "Mapping" not in text and "@Path" not in text:
                    continue
                base = ""
                cls = re.search(
                    r"@RequestMapping\s*\(\s*(?:value\s*=\s*|path\s*=\s*)?\{?\s*\"([^\"]*)\"[^)]*\)\s*"
                    r"(?:@\w+(?:\([^)]*\))?\s*)*(?:public\s+)?(?:abstract\s+)?class",
                    text,
                )
                if cls:
                    base = cls.group(1)
                for m in SPRING.finditer(text):
                    if (
                        m.group(1) == "Request"
                        and cls
                        and m.start() == text.find("@RequestMapping")
                    ):
                        continue
                    meth = m.group(1).upper() if m.group(1) != "Request" else "ANY"
                    eps.append(
                        (
                            meth,
                            (base.rstrip("/") + "/" + (m.group(3) or "").lstrip("/")).rstrip("/")
                            or "/",
                            rel,
                        )
                    )
                cpath = re.search(
                    r"@Path\s*\(\s*\"([^\"]*)\"\s*\)\s*(?:@\w+(?:\([^)]*\))?\s*)*(?:public\s+)?class",
                    text,
                )
                pending = None
                for m in JAXRS.finditer(text):
                    if m.group(1):
                        pending = m.group(1)
                    elif pending and (not cpath or m.start() != cpath.start()):
                        eps.append(
                            (
                                pending,
                                (
                                    (cpath.group(1) if cpath else "").rstrip("/")
                                    + "/"
                                    + m.group(2).lstrip("/")
                                ),
                                rel,
                            )
                        )
                        pending = None
    return sorted(specs), sorted(set(eps))[:200]


