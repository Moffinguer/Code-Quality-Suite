"""Standard repository files: the convention each one follows, validation rules for the quality
gate, and a generator that writes the missing ones from what the repository already knows
(git history, tags and branches, pom.xml / package.json, OpenAPI files, annotations).

  check(root, rel, data, branch)      (errors, warnings) for one staged file
  gather(root, gitcmd, data)          facts about the repository
  generate(root, gitcmd, data, ...)   write the missing files; [(name, what happened)]

Parts the team must write are marked with '<!-- qs:fill ... -->' (or '# qs:fill' in files with
'#' comments); the gate warns while a marker stays in a committed file.
"""

