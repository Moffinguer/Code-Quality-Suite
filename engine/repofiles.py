def t_changelog(f, gitcmd):
    """Render CHANGELOG.md from the repository facts.

    Args:
        f: the repository facts.
        gitcmd: the git command line prefix.

    Returns:
        str: the file content.
    """
    text = "# Changelog\n"
    tags = [t for t in f["tags"] if SV.is_release(t[0])][:10]
    tag_t, commit_t = link_templates(f["origin"])
    for i, (v, tag, date) in enumerate(tags):
        prev = tags[i + 1][1] if i + 1 < len(tags) else ""
        try:
            items, _ = CL.entries(gitcmd, tag, prev, commit_t) if gitcmd else ([], [])
        except RuntimeError:
            items = []
        notice = "" if items or i + 1 < len(tags) else "_First release recorded in this changelog._"
        link = tag_t.replace("{tag}", tag) if tag_t else ""
        text = CL.merge(text, v, CL.render(v, date or f["today"], items, link, notice), link)
    return text


