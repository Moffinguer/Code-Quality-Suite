def t_citation(f):
    """Render CITATION.cff from the repository facts.

    Args:
        f: the repository facts.

    Returns:
        str: the file content.
    """

    def person(a):
        """CITATION.cff author entry.

        Args:
            a: an author dict (name and commits).

        Returns:
            The YAML lines of that author.
        """
        parts = a["name"].split()
        if len(parts) < 2:
            return f'  - name: "{a["name"]}"'
        return f'  - given-names: "{parts[0]}"\n    family-names: "{" ".join(parts[1:])}"'

    authors = (
        "\n".join(person(a) for a in f["authors"][:10])
        or f'  - name: "{FILL}: author or organisation"'
    )
    out = [
        f"# Convention: Citation File Format 1.2.0 (https://citation-file-format.github.io/). "
        f"{GENERATED}",
        "cff-version: 1.2.0",
        'message: "If you use this software, please cite it as below."',
        f'title: "{f["name"]}"',
        "type: software",
        "authors:",
        authors,
    ]
    if f["description"]:
        out.append(f'abstract: "{f["description"][:400]}"')
    ver = f["released"] or f["version"]
    if ver:
        out.append(f'version: "{ver}"')
    rel = next((t for t in f["tags"] if t[0] == ver), None)
    out.append(f"date-released: '{rel[2] if rel and rel[2] else f['today']}'")
    if f["web"][1]:
        out.append(f'repository-code: "{f["web"][1]}"')
    lic = f["license"].get("name") or ""
    if re.fullmatch(r"[A-Za-z0-9.+-]+", lic):
        out.append(f'license: "{lic}"')
    return "\n".join(out) + "\n"


